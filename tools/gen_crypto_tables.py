#!/usr/bin/env python3
"""Generates user/lib/tls/tables.inc: the SHA-512 constants and the AES S-box / T-table.

Everything is derived from its mathematical definition, so there is nothing to mistype:
  SHA-512 K[i]  = first 64 fractional bits of cbrt(prime i),  H0 = same for sqrt of the first 8 primes
  SHA-384 H0    = sqrt of the 9th..16th primes
  AES S-box     = multiplicative inverse in GF(2^8) followed by the affine transform
"""
import sys

def primes(n):
    out, c = [], 2
    while len(out) < n:
        if all(c % p for p in out):
            out.append(c)
        c += 1
    return out

def iroot(x, k):
    lo, hi = 0, 1 << ((x.bit_length() // k) + 2)
    while lo < hi:
        mid = (lo + hi + 1) // 2
        if mid ** k <= x:
            lo = mid
        else:
            hi = mid - 1
    return lo

def frac64(p, k):
    # floor(frac(p^(1/k)) * 2^64)
    r = iroot(p << (64 * k), k)
    return r & ((1 << 64) - 1)

def gmul(a, b):
    r = 0
    while b:
        if b & 1:
            r ^= a
        a <<= 1
        if a & 0x100:
            a ^= 0x11b
        b >>= 1
    return r

def sbox():
    inv = [0] * 256
    for a in range(1, 256):
        for b in range(1, 256):
            if gmul(a, b) == 1:
                inv[a] = b
    s = []
    for a in range(256):
        x = inv[a]
        y = x ^ ((x << 1) | (x >> 7)) & 0xff ^ ((x << 2) | (x >> 6)) & 0xff ^ ((x << 3) | (x >> 5)) & 0xff ^ ((x << 4) | (x >> 4)) & 0xff ^ 0x63
        s.append(y & 0xff)
    return s

def rows(vals, fmt, per):
    lines = []
    for i in range(0, len(vals), per):
        lines.append("    " + ", ".join(fmt % v for v in vals[i:i + per]) + ",")
    return "\n".join(lines)

P = primes(80)
K = [frac64(p, 3) for p in P]
H512 = [frac64(p, 2) for p in P[:8]]
H384 = [frac64(p, 2) for p in P[8:16]]
S = sbox()
assert S[0] == 0x63 and S[1] == 0x7c and S[0x53] == 0xed
T0 = [(gmul(S[x], 2) << 24) | (S[x] << 16) | (S[x] << 8) | gmul(S[x], 3) for x in range(256)]

out = ["/* Generated by tools/gen_crypto_tables.py; do not edit. */", ""]
out += ["static const uint64_t SHA512_K[80] = {", rows(K, "0x%016xULL", 2), "};", ""]
out += ["static const uint64_t SHA512_H[8] = {", rows(H512, "0x%016xULL", 2), "};", ""]
out += ["static const uint64_t SHA384_H[8] = {", rows(H384, "0x%016xULL", 2), "};", ""]
out += ["static const uint8_t AES_SBOX[256] = {", rows(S, "0x%02x", 16), "};", ""]
out += ["static const uint32_t AES_TE0[256] = {", rows(T0, "0x%08x", 6), "};", ""]
open(sys.argv[1], "w").write("\n".join(out))
